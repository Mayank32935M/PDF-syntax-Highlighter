/**
 * syntax-highlighter.js
 * Tokenizes Python source code using Highlight.js and maps syntax tokens
 * to VS Code Light+ (default) or Dark+ themes.
 *
 * Produces discrete token runs with explicit colors for both the live HTML preview
 * and docx.js TextRun generation.
 */

const SyntaxHighlighter = (() => {

  // ── VS Code Light+ Theme Colors ──────────────────────────────────────────────
  const LIGHT_PLUS = {
    'keyword':          '#0000FF',  // Blue (def, if, elif, else, return, class, import, for, while, in)
    'built_in':         '#795E26',  // Dark gold / brown (print, input, float, int, len, range, str)
    'title':            '#795E26',  // Function & method definition names
    'title.function_':  '#795E26',
    'title.class_':     '#267F99',  // Teal class names
    'string':           '#A31515',  // Dark red string literals
    'string.special':   '#A31515',
    'number':           '#098658',  // Dark green numbers
    'comment':          '#008000',  // Green comments
    'operator':         '#000000',
    'punctuation':      '#000000',
    'variable':         '#001080',  // Dark navy variable names
    'params':           '#001080',
    'attr':             '#001080',
    'literal':          '#0000FF',  // True, False, None
    'name':             '#001080',
    'type':             '#267F99',
    'meta':             '#795E26',
    'default':          '#000000',
  };

  // ── VS Code Dark+ Theme Colors ───────────────────────────────────────────────
  const DARK_PLUS = {
    'keyword':          '#569CD6',  // Light blue
    'built_in':         '#DCDCAA',  // Soft yellow
    'title':            '#DCDCAA',  // Yellow
    'title.function_':  '#DCDCAA',
    'title.class_':     '#4EC9B0',  // Teal
    'string':           '#CE9178',  // Soft orange-brown
    'string.special':   '#CE9178',
    'number':           '#B5CEA8',  // Light pale green
    'comment':          '#6A9955',  // Medium green
    'operator':         '#D4D4D4',
    'punctuation':      '#D4D4D4',
    'variable':         '#9CDCFE',  // Light sky blue
    'params':           '#9CDCFE',
    'attr':             '#9CDCFE',
    'literal':          '#569CD6',
    'name':             '#9CDCFE',
    'type':             '#4EC9B0',
    'meta':             '#DCDCAA',
    'default':          '#D4D4D4',
  };

  const THEMES = {
    'light': LIGHT_PLUS,
    'dark':  DARK_PLUS,
  };

  let currentTheme = 'light';

  function setTheme(themeName) {
    if (THEMES[themeName]) currentTheme = themeName;
  }

  function getTheme() {
    return currentTheme;
  }

  /**
   * Determine hex color for a given CSS class name under the selected theme.
   */
  function colorFor(cls, theme) {
    const palette = THEMES[theme] || THEMES['light'];
    if (!cls) return palette['default'];

    const classes = cls.split(/\s+/).map(c => c.replace(/^hljs-/, ''));
    if (classes.includes('class_')) return palette['title.class_'] || palette['title'] || palette['default'];
    if (classes.includes('function_')) return palette['title.function_'] || palette['title'] || palette['default'];
    for (const c of classes) {
      if (palette[c]) return palette[c];
    }
    return palette['default'];
  }

  /**
   * Tokenize a single line of Python code.
   * Returns an array of { text, color, bold, italic } token runs.
   */
  function tokenizeLine(codeLine, theme) {
    if (!codeLine || codeLine.trim() === '') {
      return [{ text: codeLine || '', color: null, italic: false }];
    }

    const hljs = window.hljs || (typeof globalThis !== 'undefined' ? globalThis.hljs : null);
    if (!hljs) {
      return [{ text: codeLine, color: null, italic: false }];
    }

    let result;
    try {
      result = hljs.highlight(codeLine, { language: 'python', ignoreIllegals: true });
    } catch (e) {
      return [{ text: codeLine, color: null, italic: false }];
    }

    return parseHljsHtml(result.value, theme || currentTheme);
  }

  /**
   * Parse the HTML generated by highlight.js into structured token runs.
   */
  function parseHljsHtml(html, theme) {
    const tokens = [];
    let pos = 0;
    const classStack = [];

    function currentClass() {
      return classStack.length > 0 ? classStack[classStack.length - 1] : '';
    }

    while (pos < html.length) {
      if (html[pos] === '<') {
        const tagEnd = html.indexOf('>', pos);
        if (tagEnd === -1) break;
        const tag = html.slice(pos, tagEnd + 1);

        if (tag.startsWith('</')) {
          classStack.pop();
        } else {
          const m = tag.match(/class="([^"]+)"/);
          classStack.push(m ? m[1] : '');
        }
        pos = tagEnd + 1;
      } else {
        const nextTag = html.indexOf('<', pos);
        const end = nextTag === -1 ? html.length : nextTag;
        const rawText = html.slice(pos, end);
        const text = unescapeHtml(rawText);

        if (text) {
          const cls = currentClass();
          tokens.push({
            text,
            color: colorFor(cls, theme),
            bold: false,
            italic: cls.includes('comment'),
          });
        }
        pos = end;
      }
    }

    return tokens;
  }

  function unescapeHtml(str) {
    return str
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&quot;/g, '"')
      .replace(/&#39;/g, "'")
      .replace(/&#x27;/g, "'");
  }

  function escapeHtml(str) {
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /**
   * Build an HTML preview snippet with syntax highlighting.
   */
  function buildHighlightedHtml(codeLines, theme) {
    const thm = theme || currentTheme;
    const lines = codeLines.map((line, idx) => {
      const tokens = tokenizeLine(line, thm);
      const spans = tokens.map(tok => {
        if (!tok.color || tok.color === THEMES[thm]['default']) {
          return escapeHtml(tok.text);
        }
        const style = `color:${tok.color}${tok.italic ? ';font-style:italic' : ''}`;
        return `<span style="${style}">${escapeHtml(tok.text)}</span>`;
      }).join('');
      const lineNumStr = String(idx + 1).padStart(3, ' ');
      return `<span class="ln">${lineNumStr}</span>  ${spans}`;
    });
    return lines.join('\n');
  }

  return {
    setTheme,
    getTheme,
    tokenizeLine,
    buildHighlightedHtml,
    THEMES,
    LIGHT_PLUS,
    DARK_PLUS,
  };
})();

window.SyntaxHighlighter = SyntaxHighlighter;
